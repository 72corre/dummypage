// フルネーム（スタイル記号つきを含む）→ 枠内表示名。
// 表に無い名前はそのまま返す。末尾のスタイル記号（R/C/B）は、
// 外した本体が表にある時だけ記号として扱い、短縮名の後ろに付け直す。
export function slotShortName(name) {
  if (!name) return name;
  if (Object.prototype.hasOwnProperty.call(SHORT_SLOT_NAMES, name)) {
    return SHORT_SLOT_NAMES[name];
  }
  const m = /^(.+)([RCB])$/.exec(name);
  if (m && Object.prototype.hasOwnProperty.call(SHORT_SLOT_NAMES, m[1])) {
    return SHORT_SLOT_NAMES[m[1]] + m[2];
  }
  return name;
}
